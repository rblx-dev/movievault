// Post-processes i18n.translations.ts so every {{...}} placeholder is one of
// the canonical tokens: TITLE, QUERY, COUNT, DATE, DEPARTMENT, NAMES.
// (Google's GTX endpoint translates some token texts, e.g. {{title}} -> {{DATUM}}.)
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const FILE = join(__dirname, "..", "src", "lib", "i18n.translations.ts");

const SINGLE_TOKEN_KEYS = {
  "hero.open": "TITLE",
  "poster.alt": "TITLE",
  "person.knownForDept": "DEPARTMENT",
  "person.born": "DATE",
  "person.died": "DATE",
  "person.aka": "NAMES",
};
const TWO_TOKEN_KEYS = ["search.resultFor", "search.resultsFor"];

const canonical = async () => {
  const mod = await import(pathToFileURL(FILE).href + `?t=${Date.now()}`);
  const strings = structuredClone(mod.uiStrings);
  const anomalies = [];
  let fixed = 0;

  for (const lang of Object.keys(strings)) {
    const dict = strings[lang];
    for (const key of Object.keys(SINGLE_TOKEN_KEYS)) {
      const text = dict[key];
      const tokens = [...text.matchAll(/\{\{([^}]+)\}\}/g)];
      if (tokens.length === 0) continue;
      if (tokens.length > 1) {
        anomalies.push(`${lang}.${key}: ${tokens.length} tokens in "${text}"`);
        continue;
      }
      const canonicalToken = `{{${SINGLE_TOKEN_KEYS[key]}}}`;
      if (tokens[0][0] !== canonicalToken) {
        dict[key] = text.replace(tokens[0][0], canonicalToken);
        fixed += 1;
      }
    }
    for (const key of TWO_TOKEN_KEYS) {
      const text = dict[key];
      const tokens = [...text.matchAll(/\{\{([^}]+)\}\}/g)];
      for (const m of tokens) {
        const inner = m[1].trim();
        const upper = inner.toUpperCase();
        let canonicalToken = null;
        if (upper === "COUNT" || upper === "ЦОУНТ") canonicalToken = "{{COUNT}}";
        else if (upper === "QUERY" || upper === "КУЕРИ") canonicalToken = "{{QUERY}}";
        else anomalies.push(`${lang}.${key}: unmapped token {{${inner}}} in "${text}"`);
        if (canonicalToken && m[0] !== canonicalToken) {
          dict[key] = dict[key].replace(m[0], canonicalToken);
          fixed += 1;
        }
      }
    }
  }

  for (const lang of Object.keys(strings)) {
    const dict = strings[lang];
    for (const [key, value] of Object.entries(dict)) {
      const leftover = [...value.matchAll(/\{\{([^}]+)\}\}/g)];
      for (const m of leftover) {
        const upper = m[1].trim().toUpperCase();
        if (!["TITLE", "QUERY", "COUNT", "DATE", "DEPARTMENT", "NAMES"].includes(upper)) {
          anomalies.push(`${lang}.${key}: leftover token {{${m[1].trim()}}} in "${value}"`);
        }
      }
    }
  }

  const langCodes = mod.uiLanguageCodes;
  const body = [
    "// AUTO-GENERATED by tools/generate-i18n.mjs — do not edit by hand.",
    "export const uiLanguageCodes = " + JSON.stringify(langCodes) + ";",
    "",
    "export const uiStrings: Record<string, Record<string, string>> = {",
  ];
  for (const [lang, dict] of Object.entries(strings)) {
    body.push(`  ${JSON.stringify(lang)}: {`);
    for (const [key, value] of Object.entries(dict)) {
      body.push(`    ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
    }
    body.push(`  },`);
  }
  body.push("};");
  body.push("");

  writeFileSync(FILE, body.join("\n"), "utf8");
  console.log(`fixed ${fixed} tokens`);
  if (anomalies.length) {
    console.log("ANOMALIES:");
    for (const a of anomalies) console.log("  " + a);
  } else {
    console.log("no anomalies");
  }
};

canonical().catch((e) => {
  console.error(e);
  process.exit(1);
});
